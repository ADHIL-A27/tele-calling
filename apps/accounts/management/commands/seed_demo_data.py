"""Creates a self-contained set of DEMO records (college, courses, staff
accounts, leads, calls, follow-ups) for exploring the CRM. Every demo user's
username is prefixed with 'demo_' and every demo lead's remarks field is
tagged '[DEMO DATA]' so these records are always distinguishable from real
student data and can be bulk-deleted safely.
"""

import random
from datetime import timedelta

from django.core.management.base import BaseCommand
from django.utils import timezone

from apps.accounts.models import CustomUser, Role, TelecallerProfile
from apps.courses.models import AcademicSession, College, Course
from apps.leads.models import Campaign, LeadPriority, LeadSource, LeadStage, StudentLead
from apps.telecalling.models import DEFAULT_CALL_OUTCOMES, CallAttempt, CallOutcome

FIRST_NAMES = ["Aarav", "Diya", "Rohan", "Ananya", "Kabir", "Isha", "Vihaan", "Meera", "Arjun", "Priya"]
LAST_NAMES = ["Nair", "Menon", "Pillai", "Varma", "Iyer", "Reddy", "Shah", "Kulkarni", "Joshi", "Rao"]


class Command(BaseCommand):
    help = "Seed demo data (college, courses, staff, leads, calls). Safe to re-run."

    def add_arguments(self, parser):
        parser.add_argument("--leads", type=int, default=120, help="Number of demo leads to create.")

    def handle(self, *args, **options):
        self.call_command_seed_outcomes()

        college, _ = College.objects.get_or_create(
            code="DEMO01", defaults={"name": "Demo Institute of Technology", "email": "info@demo-institute.test"}
        )
        session, _ = AcademicSession.objects.get_or_create(
            name="2025-2026", defaults={"start_date": "2025-06-01", "end_date": "2026-05-31", "is_current": True}
        )

        course_specs = [("BCA", "Bachelor of Computer Applications"), ("BBA", "Bachelor of Business Administration"),
                         ("BCom", "Bachelor of Commerce"), ("MCA", "Master of Computer Applications"),
                         ("MBA", "Master of Business Administration")]
        courses = []
        for code, name in course_specs:
            course, _ = Course.objects.get_or_create(
                college=college, code=code,
                defaults={"name": name, "duration": "3 Years", "total_seats": 60, "available_seats": 40, "academic_session": session},
            )
            courses.append(course)

        admin_user, created = CustomUser.objects.get_or_create(
            username="demo_admin",
            defaults={"role": Role.ADMIN, "first_name": "Demo", "last_name": "Admin", "is_staff": True, "college": college},
        )
        if created:
            admin_user.set_password("DemoPass123!")
            admin_user.save()

        telecallers = []
        for i in range(1, 4):
            user, created = CustomUser.objects.get_or_create(
                username=f"demo_caller{i}",
                defaults={"role": Role.TELECALLER, "first_name": f"Demo Caller {i}", "last_name": ""},
            )
            if created:
                user.set_password("DemoPass123!")
                user.save()
            TelecallerProfile.objects.get_or_create(user=user, defaults={"manager": admin_user, "max_active_leads": 150})
            telecallers.append(user)

        source, _ = LeadSource.objects.get_or_create(name="Demo Website Enquiry")
        campaign, _ = Campaign.objects.get_or_create(
            name="Demo Admission Drive 2026", college=college, academic_session=session
        )

        outcomes = list(CallOutcome.objects.all())
        stages = list(LeadStage)
        priorities = list(LeadPriority)
        n = options["leads"]
        created_leads = 0

        for i in range(n):
            phone = f"9{random.randint(100000000, 999999999)}"
            name = f"{random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}"
            if StudentLead.objects.filter(student_phone_normalized=phone).exists():
                continue
            owner = random.choice(telecallers) if random.random() > 0.3 else None
            lead = StudentLead.objects.create(
                student_name=name,
                student_phone=phone,
                parent_name=f"{random.choice(LAST_NAMES)} Family",
                parent_phone=f"9{random.randint(100000000, 999999999)}",
                email=f"{name.split()[0].lower()}{i}@demo-mail.test",
                district="Ernakulam",
                location="Kochi",
                qualification="12th Standard",
                interested_course=random.choice(courses),
                lead_source=source,
                campaign=campaign,
                academic_year=session,
                stage=random.choice(stages[:6]),
                priority=random.choice(priorities),
                current_owner=owner,
                remarks="[DEMO DATA] generated by seed_demo_data",
                created_by=admin_user,
            )
            created_leads += 1

            if owner and outcomes and random.random() > 0.4:
                for _ in range(random.randint(1, 3)):
                    call_dt = timezone.now() - timedelta(days=random.randint(0, 20))
                    CallAttempt.objects.create(
                        lead=lead,
                        telecaller=owner,
                        outcome=random.choice(outcomes),
                        call_date=call_dt.date(),
                        call_time=call_dt.time(),
                        duration_seconds=random.randint(20, 600),
                        remarks="[DEMO DATA] auto-generated call log",
                    )
                lead.last_call_at = timezone.now()
                lead.save(update_fields=["last_call_at"])

        self.stdout.write(self.style.SUCCESS(
            f"Demo data ready: college, {len(courses)} courses, {1 + len(telecallers)} staff accounts, "
            f"{created_leads} new leads. Default password for demo accounts: DemoPass123!"
        ))

    def call_command_seed_outcomes(self):
        for order, (name, slug, category, requires_follow_up) in enumerate(DEFAULT_CALL_OUTCOMES):
            CallOutcome.objects.get_or_create(
                slug=slug,
                defaults={"name": name, "category": category, "requires_follow_up": requires_follow_up, "display_order": order},
            )
